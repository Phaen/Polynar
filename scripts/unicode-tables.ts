/**
 * Prints src/predictor/unicode-tables.ts: the one-to-one simple case pairs and the letter/number
 * ranges of the running Node's Unicode data.
 *
 *   npx tsx scripts/unicode-tables.ts > src/predictor/unicode-tables.ts
 */

const MAX_CP = 0x10ffff;
const WIDTH = 100;
const LETTER_OR_NUMBER = /[\p{L}\p{N}]/u;

/** The single code point of a string, or -1 when it has none or several. */
function single(s: string): number {
  const cp = s.codePointAt(0)!;
  return s.length === (cp > 0xffff ? 2 : 1) ? cp : -1;
}

/** Pairs (lower, upper) where each side maps to the other as one code point, ordered by lower. */
function casePairs(): [number, number][] {
  const pairs: [number, number][] = [];
  for (let cp = 0; cp <= MAX_CP; cp++) {
    const ch = String.fromCodePoint(cp);
    const up = single(ch.toUpperCase());
    if (up < 0 || up === cp) continue;
    if (single(String.fromCodePoint(up).toLowerCase()) !== cp) continue;
    pairs.push([cp, up]);
  }
  const seen = new Set<number>();
  for (const [lo, up] of pairs) {
    if (seen.has(lo) || seen.has(up)) throw new Error(`case pair ${lo}/${up} is not disjoint`);
    seen.add(lo);
    seen.add(up);
  }
  return pairs;
}

/** The maximal runs of code points that are letters or numbers, as [start, end] pairs. */
function letterNumberRanges(): [number, number][] {
  const ranges: [number, number][] = [];
  let start = -1;
  for (let cp = 0; cp <= MAX_CP + 1; cp++) {
    const yes = cp <= MAX_CP && LETTER_OR_NUMBER.test(String.fromCodePoint(cp));
    if (yes && start < 0) start = cp;
    if (!yes && start >= 0) {
      ranges.push([start, cp - 1]);
      start = -1;
    }
  }
  return ranges;
}

/** An Int32Array literal laid out as Prettier lays out a number array that does not fit a line. */
function literal(name: string, values: number[]): string {
  const lines: string[] = [];
  let line = '  ';
  for (const v of values) {
    const item = `${v},`;
    if (line.length > 2 && line.length + 1 + item.length > WIDTH) {
      lines.push(line);
      line = '  ';
    }
    line += (line.length > 2 ? ' ' : '') + item;
  }
  lines.push(line);
  return `export const ${name} = new Int32Array([\n${lines.join('\n')}\n]);\n`;
}

const pairs = casePairs();
const byUpper = pairs.map(([lo, up]): [number, number] => [up, lo]).sort((a, b) => a[0] - b[0]);

process.stdout.write(
  [
    `// Generated by scripts/unicode-tables.ts from Unicode ${process.versions.unicode}.`,
    '',
    '/** Alternating [lower, upper] of every one-to-one case pair, ordered by lower. */',
    literal('CASE_PAIRS', pairs.flat()),
    '/** The same pairs as alternating [upper, lower], ordered by upper. */',
    literal('CASE_PAIRS_BY_UPPER', byUpper.flat()),
    '/** Alternating [start, end] of the maximal runs of code points matching /[\\p{L}\\p{N}]/u. */',
    literal('LN_RANGES', letterNumberRanges().flat()),
  ].join('\n')
);

export {};
