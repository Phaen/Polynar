/**
 * Integer-exact arithmetic of the predictor.
 *
 * Every value is an integer of magnitude below 2^53 held in a `number` or a typed array. The
 * helpers here are the only place that divides; each is exact on the domain stated at it.
 *
 * Proof of `mulShr`. Let a = a1 * 2^26 + a0 with 0 <= a0 < 2^26, so a1 < 2^26 whenever a < 2^52.
 * With b < 2^26, X = a1 * b and Y = a0 * b are below 2^52, and a * b = X * 2^26 + Y.
 * - For k >= 26 let s = k - 26, q1 = floor(X / 2^s) and r1 = X - q1 * 2^s, so r1 < 2^s. Then
 *   X * 2^26 = q1 * 2^k + r1 * 2^26, hence floor(a * b / 2^k) = q1 + floor((r1 * 2^26 + Y) / 2^k).
 *   Here r1 * 2^26 < 2^k <= 2^52 and Y < 2^52, so the sum is below 2^53 and every step is exact.
 * - For k < 26, X * 2^26 / 2^k = X * 2^(26 - k) is an integer, hence
 *   floor(a * b / 2^k) = X * 2^(26 - k) + floor(Y / 2^k). Both terms are exact while the result is
 *   below 2^53, which is the stated domain for k < 26.
 *
 * Proof of `div`. Let y = a / b for an integer |a| < 2^53 and an integer b >= 1, and Q = floor(y).
 * The IEEE quotient fl(y) is correctly rounded, so |fl(y) - y| <= |y| * 2^-53, and rounding is
 * monotone, so fl(y) never crosses an integer that y does not reach. floor(fl(y)) could exceed Q
 * only when fl(y) reaches Q + 1 > y, which needs (Q + 1) - y <= |y| * 2^-53, that is
 * (Q + 1) * b - a <= |a| * 2^-53 < 1. The left side is a positive integer, so this never happens
 * and Math.floor(a / b) is Q. `shr` multiplies by the exact power 2^-k, which is exact for any
 * integer below 2^53, before the floor.
 *
 * `LOG2_TABLE` and `EXP2_TABLE` are data generated by scripts/arith-tables.ts.
 */

import { EXP2_TABLE, LOG2_TABLE } from './arith-tables';

export { EXP2_TABLE, LOG2_TABLE };

/** Fractional bits of log-domain values (bits, base 2). */
export const RB = 24;
/** Bits of the largest mass of a step after block scaling. */
export const SB = 36;
/** Bits an accumulator is brought under before products with 16-bit precision. */
export const HB = 30;
/** Bits of shares and probabilities. */
export const PB = 16;

/** Exact powers of two, 2^0 to 2^52. */
export const POW2 = new Float64Array(53);
POW2[0] = 1;
for (let i = 1; i < POW2.length; i++) {
  POW2[i] = POW2[i - 1] * 2;
}

/** 1.0 in RB fixed point. */
export const ONE = POW2[RB];
/** Below this exponent a weight is 0. */
export const E_MIN = -48 * ONE;

/** Index bits of both tables. */
const TABLE_BITS = 12;
const TWO_26 = POW2[26];

/** Exact powers of two, 2^0 to 2^-52. */
const POW2_NEG = new Float64Array(53);
POW2_NEG[0] = 1;
for (let i = 1; i < POW2_NEG.length; i++) {
  POW2_NEG[i] = POW2_NEG[i - 1] * 0.5;
}

// Module bindings of the tables: a re-exported import is read through a getter once transpiled
// to CommonJS.
const EXP2 = EXP2_TABLE;
const LOG2 = LOG2_TABLE;
/** 2^-RB and 2^-(RB - TABLE_BITS): the shifts of `exp2Fix` as exact multiplications. */
const INV_ONE = POW2_NEG[RB];
const INV_FRAC = POW2_NEG[RB - TABLE_BITS];

/** floor(a / b) for integers |a| < 2^53 and b >= 1. */
export function div(a: number, b: number): number {
  return Math.floor(a / b);
}

/** floor(a / 2^k), also for negative a; 0 <= k <= 52. */
export function shr(a: number, k: number): number {
  return Math.floor(a * POW2_NEG[k]);
}

/** a * 2^k; the caller keeps the result below 2^53. */
export function shl(a: number, k: number): number {
  return a * POW2[k];
}

/** floor(a * b / 2^k) for 0 <= a < 2^52, 0 <= b < 2^26, 0 <= k <= 52, and a * b / 2^k < 2^53 when k < 26. */
export function mulShr(a: number, b: number, k: number): number {
  const a1 = div(a, TWO_26);
  const a0 = a - a1 * TWO_26;
  const x = a1 * b;
  const y = a0 * b;
  if (k < 26) {
    return x * POW2[26 - k] + div(y, POW2[k]);
  }
  const s = POW2[k - 26];
  const q1 = div(x, s);
  const r1 = x - q1 * s;
  return q1 + div(r1 * TWO_26 + y, POW2[k]);
}

/** floor(a * b / c) for 0 <= a < 2^27, 0 <= b < 2^26 and 0 < c. */
export function mulDiv(a: number, b: number, c: number): number {
  return div(a * b, c);
}

/** The bits of x: 0 for 0, else the position of the leading one plus one; 0 <= x < 2^53. */
export function bitlen(x: number): number {
  if (x < POW2[32]) {
    return 32 - Math.clz32(x);
  }
  return 32 + bitlen(div(x, POW2[32]));
}

/** log2(x) in RB fixed point for an integer 1 <= x < 2^53, defined by `LOG2_TABLE`. */
export function log2Fix(x: number): number {
  const k = bitlen(x) - 1;
  const frac =
    k >= TABLE_BITS ? div(x, POW2[k - TABLE_BITS]) - 4096 : x * POW2[TABLE_BITS - k] - 4096;
  return k * ONE + LOG2[frac];
}

/**
 * 2^(e / ONE) floored to an integer, for e in RB fixed point with e <= 52 * ONE + ONE - 1; 0 when
 * e < E_MIN or when the result floors to 0.
 */
export function exp2Fix(e: number): number {
  if (e < E_MIN) {
    return 0;
  }
  const q = Math.floor(e * INV_ONE);
  if (q > 52) {
    throw new RangeError(`exp2Fix: exponent ${q} exceeds 52`);
  }
  const m = EXP2[Math.floor((e - q * ONE) * INV_FRAC)];
  if (q >= 24) {
    return m * POW2[q - 24];
  }
  const s = 24 - q;
  return s > 52 ? 0 : Math.floor(m * POW2_NEG[s]);
}

/** x / 2^k rounded to nearest, ties upward; 1 <= k <= 52. */
export function round(x: number, k: number): number {
  return shr(x + POW2[k - 1], k);
}

/** Shifts values[0..n) right by the same amount until the largest is below 2^bits; returns the shift. */
export function scaleDown(values: Float64Array, n: number, bits: number): number {
  let max = 0;
  for (let i = 0; i < n; i++) {
    if (values[i] > max) {
      max = values[i];
    }
  }
  const excess = bitlen(max) - bits;
  const s = excess > 0 ? excess : 0;
  if (s > 0) {
    for (let i = 0; i < n; i++) {
      values[i] = shr(values[i], s);
    }
  }
  return s;
}

/** x limited to [lo, hi]. */
export function clampi(x: number, lo: number, hi: number): number {
  return x < lo ? lo : x > hi ? hi : x;
}

/**
 * Lowercase hex of the 32-bit FNV-1a hash over the little-endian bytes of LOG2_TABLE then
 * EXP2_TABLE. Priors record it to show that they were trained against the same tables.
 */
function tablesDigest(): string {
  let h = 0x811c9dc5;
  for (const table of [LOG2_TABLE, EXP2_TABLE]) {
    for (let i = 0; i < table.length; i++) {
      for (let byte = 0; byte < 4; byte++) {
        // Bit operators on a 32-bit hash word, as in keymap.ts.
        h = Math.imul(h ^ ((table[i] >>> (8 * byte)) & 0xff), 0x01000193);
      }
    }
  }
  return (h >>> 0).toString(16).padStart(8, '0');
}

export const TABLES_DIGEST: string = tablesDigest();
